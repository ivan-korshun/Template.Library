IF NOT EXISTS(SELECT principal_id FROM sys.server_principals WHERE name = '$(CONSUMER_LOGIN_NAME)')
BEGIN
  CREATE LOGIN $(CONSUMER_LOGIN_NAME)
  WITH PASSWORD = '$(CONSUMER_LOGIN_PASSWORD)'
END

IF NOT EXISTS(SELECT principal_id FROM sys.server_principals WHERE name = '$(OWNER_LOGIN_NAME)')
BEGIN
  CREATE LOGIN $(OWNER_LOGIN_NAME)
  WITH PASSWORD = '$(OWNER_LOGIN_PASSWORD)'
END
